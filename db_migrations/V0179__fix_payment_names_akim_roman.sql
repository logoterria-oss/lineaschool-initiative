-- Восстанавливаем имена плательщиков, испорченные старым подбором карточки CRM.
-- До 26.09 код записывал в payment_leads.name НАЙДЕННУЮ карточку CRM вместо
-- имени, которое указал родитель. При ошибке подбора оплата оказывалась
-- на чужом ученике.

-- 16.09: платил Корлыханов Аким (лид #119, Корлыханова Анна Сергеевна).
-- Карточки Корлыханова в кэше CRM тогда ещё не было, и подбор по имени
-- «Аким» привязал оплату к единственному Акиму в базе — Нестеровскому.
UPDATE payment_leads
SET name = 'Корлыханов Аким Олегович',
    crm_name = 'Корлыханов Аким Олегович'
WHERE id = 1056
  AND order_id = 'ORDER_1789536966734'
  AND name = 'Аким Нестеровский';

-- 23.09: «Роман» — это не «родитель не указал фамилию», а результат той же
-- подмены: в CRM есть карточка, названная просто «Роман» (лид #127,
-- Соловьева Елена Дмитриевна), и подбор по одному слову затёр введённое ФИО.
-- Исходное ФИО не сохранилось, поэтому фиксируем только карточку CRM.
UPDATE payment_leads
SET crm_name = 'Роман'
WHERE id = 1073
  AND order_id = 'ORDER_1790164181056';
