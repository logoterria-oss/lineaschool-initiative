-- Починка смены Федоровой Анастасии (id=12).
--
-- Что произошло: 12 сентября она открыла смену в 07:53 и ушла уже за
-- полночь — в 01:52 13 сентября. Кнопка «Смена закончена» записала
-- отметку ухода в ТЕКУЩИЙ календарный день (13-е), где смена ещё не
-- открывалась. Из-за этого 12-е осталось «не закрыто», а 13-е получило
-- время закрытия 01:52 без открытия. Позже, в 11:07, она нажала
-- «На смене» — и в 13-м числе сошлись открытие 11:07 и закрытие 01:52,
-- то есть уход «раньше» прихода.
--
-- Чиним: уход 01:52 переносим на смену 12 сентября, которой он
-- фактически принадлежит, а сегодняшнюю смену оставляем открытой.

-- 12 сентября: смена закрыта в 01:52 ночи 13-го
UPDATE t_p93118852_lineaschool_initiati.admin_shifts
SET finished_at = TIMESTAMP '2026-09-13 01:52:32.527486',
    updated_at = (now() AT TIME ZONE 'Europe/Moscow')
WHERE staff_id = 12 AND shift_date = DATE '2026-09-12';

-- 13 сентября: смена открыта в 11:07 и ещё идёт
UPDATE t_p93118852_lineaschool_initiati.admin_shifts
