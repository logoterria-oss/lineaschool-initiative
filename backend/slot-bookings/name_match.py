# Окончания отчеств
PATRONYMIC_RE = re.compile(r'(вич|вна|чна|ична|овна|евна|ьевна|ьевич)$')

# Окончания фамилий (в том числе женский род)
SURNAME_RE = re.compile(
    r'(ов|ова|ев|ева|ёв|ёва|ин|ина|ын|ына|ский|ская|цкий|цкая|'
    r'енко|ко|ук|юк|ян|швили|дзе|ых|их|ой|ая)$'
)


def _clean(raw: Optional[str]) -> str:
    '''Нижний регистр, «ё» → «е», дефисы и лишние пробелы убраны.'''
    s = (raw or '').lower().replace('ё', 'е')
    s = re.sub(r'[^a-zа-я\s-]', ' ', s)
    s = s.replace('-', ' ')
    return re.sub(r'\s+', ' ', s).strip()


def _canon_surname(word: str) -> str:
    '''Фамилия без признака рода: «Иванова» и «Иванов» — одна семья.'''
    for female, male in (
        ('ская', 'ский'), ('цкая', 'цкий'), ('ая', 'ий'),
    ):
        if word.endswith(female):
            return word[: -len(female)] + male
    # «Иванова» → «Иванов», «Борычива» → «Борычив»: конечная «а» у длинной
    # фамилии почти всегда женский род. Так опечатка в середине слова
    # остаётся единственным расхождением и прощается при сравнении.
    if len(word) > 4 and word.endswith('а'):
        return word[:-1]
    return word


def _canon_first(word: str) -> str:
    '''Уменьшительное имя → полное: «Маша» → «Мария».'''
    return DIMINUTIVES.get(word, word)


def _levenshtein(a: str, b: str) -> int:
    '''Сколько правок отделяет одно слово от другого.'''
    if a == b:
        return 0
    if abs(len(a) - len(b)) > 2:
        return 3
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]


def _close(a: str, b: str) -> bool:
    '''Слова считаются одним и тем же с поправкой на опечатку.

    Одну правку прощаем только длинным словам: в коротких «Оля» и «Аля»
    одна буква — это уже разные дети.
    '''
    if a == b:
        return True
    if min(len(a), len(b)) >= 5:
        return _levenshtein(a, b) <= 1
    return False


def parse_name(raw: Optional[str]) -> Tuple[str, str]:
    '''Разбираем строку на (фамилия, имя) в каноническом виде.

    Отчество отбрасываем, порядок слов значения не имеет.
    Если разобрать не удалось — возвращаем пустые строки.
    '''
    words = [w for w in _clean(raw).split() if len(w) > 1]
    if not words:
        return '', ''

    # Отчество нам не нужно — по нему детей не различают
    words = [w for w in words if not PATRONYMIC_RE.search(w)] or words

    if len(words) == 1:
        return '', _canon_first(words[0])

    known = [w for w in words if w in DIMINUTIVES]
    # Слово, которое не является известным именем, — почти наверняка фамилия.
    # Это важнее окончания: «Ким» на фамилию не похоже, но кроме него
    # в «Анна-Мария Ким» фамилии взяться неоткуда.
    unknown = [w for w in words if w not in DIMINUTIVES]
    by_ending = [w for w in unknown if SURNAME_RE.search(w)]

    if known:
        first = known[0]
        surname = (by_ending or unknown or [w for w in words if w != first])
        surname = surname[0] if surname else ''
    elif by_ending:
        surname = by_ending[0]
        first = next((w for w in words if w != surname), '')
    else:
        # Ничего не узнали — считаем первым словом имя
        first, surname = words[0], words[1]

    return _canon_surname(surname), _canon_first(first)


def same_child(a: Optional[str], b: Optional[str]) -> bool:
    '''Один ли это ребёнок.

    Совпасть должны и фамилия, и имя — иначе братья и сёстры склеятся
    в одну заявку. Если фамилии нет ни у одного из имён, сверяем по имени.
    '''
    sa, fa = parse_name(a)
    sb, fb = parse_name(b)
    if not fa or not fb:
        return False
    if not _close(fa, fb):
        return False
    if sa and sb:
        return _close(sa, sb)
    # Фамилию указали не везде — по одному имени связывать рискованно
    return False