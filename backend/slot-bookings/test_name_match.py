'''Проверки распознавания имени ребёнка.

Запуск: python3 test_name_match.py (из папки backend/slot-bookings)
'''

from name_match import parse_name, same_child

# (имя А, имя Б, один ли это ребёнок)
CASES = [
    # Один и тот же ребёнок
    ('Маша Иванова', 'Мария Иванова', True),
    ('Маша Иванова', 'Иванова Маша', True),
    ('Маша Иванова', 'Иванова Мария Сергеевна', True),
    ('Маша Иванова', 'Мирия Иванова', True),          # опечатка в имени
    ('Полина Борычева', 'Борычива Полина', True),      # опечатка в фамилии
    ('Полина Борычева', 'Поля Борычева', True),
    ('Настя Канкулова', 'Канкулова Анастасия', True),
    ('Саша Иванов', 'Александра Иванова', True),
    ('Артём Ерёмин', 'Артем Еремин', True),            # «ё» и регистр
    ('Анна-Мария Ким', 'Ким Анна Мария', True),        # двойное имя, короткая фамилия
    ('МАРИЯ ИВАНОВА', 'иванова  маша', True),

    # Разные дети — склеивать нельзя
    ('Маша Иванова', 'Даша Иванова', False),           # сёстры
    ('Маша Иванова', 'Маша Петрова', False),           # разные фамилии
    ('Маша Иванова', 'Маша Иванченко', False),
    ('Соня Петренко', 'Соня Петрова', False),
    ('Настя Канкулова', 'Настя Камнева', False),
    ('Тимур Ким', 'Тимофей Ким', False),
]


def main():
    failed = 0
    for a, b, expected in CASES:
        got = same_child(a, b)
        mark = 'OK  ' if got == expected else 'FAIL'
        if got != expected:
            failed += 1
        print(f'{mark} {a!r} ~ {b!r} = {got} | {parse_name(a)} {parse_name(b)}')
    print(f'\nвсего: {len(CASES)}, ошибок: {failed}')
    return 1 if failed else 0


if __name__ == '__main__':
    raise SystemExit(main())
